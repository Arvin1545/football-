// ====================================================
// گرفتن خوشحالی یک بازیکن
// ====================================================
export function getPlayerCelebration(playerName) {
  // اگه ستاره معروف هست
  if (STAR_CELEBRATIONS[playerName]) {
    return STAR_CELEBRATIONS[playerName];
  }
  
  // وگرنه random از لیست عمومی
  const randomIndex = Math.floor(Math.random() * GENERAL_CELEBRATIONS.length);
  return GENERAL_CELEBRATIONS[randomIndex];
}

// ====================================================
// گرفتن خوشحالی برای شادی گل
// ====================================================
export function renderCelebration(player, team) {
  const celebration = getPlayerCelebration(player.name);
  
  return {
    player: player.name,
    team: team.name,
    teamColors: {
      primary: team.primary_color,
      secondary: team.secondary_color
    },
    celebration: {
      name: celebration.name,
      emoji: celebration.emoji,
      animation: celebration.animation
    }
  };
}

// ====================================================
// تعداد خوشحالی‌های ثبت‌شده
// ====================================================
export function getCelebrationCount() {
  return {
    stars: Object.keys(STAR_CELEBRATIONS).length,
    general: GENERAL_CELEBRATIONS.length,
    total: Object.keys(STAR_CELEBRATIONS).length + GENERAL_CELEBRATIONS.length
  };
}
